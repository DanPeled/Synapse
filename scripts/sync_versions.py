"""Regenerate checked-in version modules from the root ``versions.properties``.

Gradle and the Python packaging metadata read ``versions.properties`` directly.
The ``synapse`` runtime package cannot (it is installed without the repository
root), so this script writes the generated values into ``__version__.py``.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERSIONS_FILE = ROOT / "versions.properties"
OUTPUT_FILE = ROOT / "synapse_core" / "src" / "synapse" / "__version__.py"


def load_versions() -> dict[str, str]:
    versions: dict[str, str] = {}
    for line in VERSIONS_FILE.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith(("#", "!")):
            continue
        key, separator, value = line.partition("=")
        if not separator:
            raise ValueError(f"Malformed line in {VERSIONS_FILE}: {line!r}")
        versions[key.strip()] = value.strip()
    return versions


def render(versions: dict[str, str]) -> str:
    return f'''# SPDX-FileCopyrightText: 2025 Dan Peled
# SPDX-FileCopyrightText: 2026 Dan Peled
#
# SPDX-License-Identifier: GPL-3.0-or-later
#
# Generated by scripts/sync_versions.py from versions.properties. Do not edit.

from typing import Final

WPILIB_VERSION: Final[str] = "{versions["wpilibPythonVersion"]}"
WPILIB_YEAR: Final[str] = "{versions["wpilibYear"]}"
SYNAPSE_VERSION: Final[str] = "{versions["synapsePythonVersion"]}"
'''


def main() -> None:
    OUTPUT_FILE.write_text(render(load_versions()), encoding="utf-8")
    print(f"Updated {OUTPUT_FILE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
